// lectio-export-os.js
// Put this file in the SAME folder as your existing lectio.js and lectio-run.js.
// It does not replace or change lectio-run.js.
// It uses your existing Lectio sync/cache and writes browser-readable JavaScript data.
// Output: lectio-data.js containing: window.LECTIO_DATA = {...};
//
// Usage:
//   node lectio-export-os.js 12
//
// Optional: write directly into a cloned personal-os repo:
//   PERSONAL_OS_REPO=/root/personal-os node lectio-export-os.js 12

const fs = require('fs');
const path = require('path');
const lectio = require('./lectio');

const CACHE_PATH = path.join(__dirname, 'db', 'lectio-cache.json');
const REPO_PATH = process.env.PERSONAL_OS_REPO || '';
const OUTPUT_PATH = process.env.PERSONAL_OS_LECTIO_JS || (REPO_PATH ? path.join(REPO_PATH, 'lectio-data.js') : path.join(__dirname, 'lectio-data.js'));
const LATEST_SCHOOL_END = '14:55';

function timeToMinutes(value) {
  if (!value || !/^\d{1,2}:\d{2}$/.test(String(value))) return null;
  const [h, m] = String(value).split(':').map(Number);
  return h * 60 + m;
}

function clampSchoolEnd(end) {
  if (!end) return end;
  return timeToMinutes(end) > timeToMinutes(LATEST_SCHOOL_END) ? LATEST_SCHOOL_END : end;
}

function cleanTitle(value) {
  return String(value || '')
    .replace(/\s+/g, ' ')
    .replace(/\s*,?\s*lektiehj[æa]lp(er)?(?:\s+\d{1,2}\s*-\s*\d{1,2})?$/i, '')
    .trim();
}

function lessonHasRealHomework(lesson) {
  if (!lesson || lesson.cancelled || lesson.isAllDay) return false;
  if (Array.isArray(lesson.homeworkTitles) && lesson.homeworkTitles.length > 0) return true;
  if (Array.isArray(lesson.homeworkLinks) && lesson.homeworkLinks.length > 0) return true;
  const note = String(lesson.note || '').toLowerCase();
  return /\b(lektie|lektier|homework|aflever|read|solve|exercise|exercises|prepare)\b/i.test(note);
}

function loadCache() {
  if (!fs.existsSync(CACHE_PATH)) {
    throw new Error(`Missing ${CACHE_PATH}. Run: node lectio.js regular 8`);
  }
  const raw = fs.readFileSync(CACHE_PATH, 'utf8').trim();
  if (!raw) throw new Error(`${CACHE_PATH} is empty`);
  return JSON.parse(raw);
}

function allDateEntries(cache) {
  // Your lectio.js writes db/lectio-cache.json as { dates: { yyyy-mm-dd: [lessons] } }.
  // These fallbacks make the exporter tolerate slightly different cache layouts.
  if (cache && cache.dates && typeof cache.dates === 'object') return Object.entries(cache.dates);
  if (cache && cache.data && cache.data.dates && typeof cache.data.dates === 'object') return Object.entries(cache.data.dates);
  if (cache && cache.byDate && typeof cache.byDate === 'object') return Object.entries(cache.byDate);
  return [];
}

function buildPersonalOsData(cache) {
  const school = [];
  const homeworkMap = new Map();
  const dateEntries = allDateEntries(cache);

  for (const [date, lessons] of dateEntries) {
    for (const lesson of lessons || []) {
      if (!lesson || lesson.cancelled || lesson.isAllDay) continue;
      if (!lesson.start || !lesson.end) continue;
      if (timeToMinutes(lesson.start) == null || timeToMinutes(lesson.start) >= timeToMinutes(LATEST_SCHOOL_END)) continue;

      const title = cleanTitle(lesson.subject || lesson.hold || lesson.title || lesson.name || 'School');
      if (!title) continue;

      school.push({ date, start: lesson.start, end: clampSchoolEnd(lesson.end), title });

      if (lessonHasRealHomework(lesson)) {
        const subject = cleanTitle(lesson.hold || lesson.subject || title);
        homeworkMap.set(`${date}|${subject}`, { date, subject });
      }
    }
  }

  school.sort((a, b) => `${a.date} ${a.start}`.localeCompare(`${b.date} ${b.start}`));
  const homework = [...homeworkMap.values()].sort((a, b) => `${a.date} ${a.subject}`.localeCompare(`${b.date} ${b.subject}`));

  return {
    syncedAt: cache.generatedAt || cache.fetchedAt || new Date().toISOString(),
    source: 'lectio.js cache',
    dateCount: dateEntries.length,
    school,
    homework
  };
}

async function main() {
  const weeksAhead = Number(process.argv[2] || 12);
  console.log(`[personal-os] syncing Lectio ${weeksAhead} weeks ahead...`);

  const syncResult = await lectio.syncLectioRange({ weeksAhead, mode: 'personal-os-js-export' });
  if (!syncResult || syncResult.error || !syncResult.ok) {
    throw new Error(syncResult?.error || 'Lectio sync failed');
  }

  const cache = loadCache();
  const output = buildPersonalOsData(cache);

  fs.mkdirSync(path.dirname(OUTPUT_PATH), { recursive: true });
  const js = `// Auto-generated by lectio-export-os.js. Do not edit manually.\nwindow.LECTIO_DATA = ${JSON.stringify(output, null, 2)};\n`;
  fs.writeFileSync(OUTPUT_PATH, js, 'utf8');

  console.log(`[personal-os] cache dates: ${output.dateCount}`);
  console.log(`[personal-os] school items exported: ${output.school.length}`);
  console.log(`[personal-os] homework subjects exported: ${output.homework.length}`);
  console.log(`[personal-os] wrote: ${OUTPUT_PATH}`);

  if (!output.school.length) {
    console.log('[personal-os] WARNING: sync succeeded, but no school lessons were exported. Check db/lectio-cache.json shape.');
  }

  if (REPO_PATH) {
    console.log('[personal-os] Next commands:');
    console.log(`  cd ${REPO_PATH}`);
    console.log('  git add lectio-data.js');
    console.log('  git commit -m "Update Lectio data"');
    console.log('  git push');
  } else {
    console.log('[personal-os] Upload/copy this lectio-data.js into the personal-os repo root, replacing the placeholder file.');
  }
}

main().catch((err) => {
  console.error('[personal-os] export failed:', err.message);
  process.exit(1);
});
